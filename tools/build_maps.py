def write(map_id, data):
    # один ящик — одна строка, чтобы файл было удобно читать и править руками
    boxes = ",\n    ".join(json.dumps(b, ensure_ascii=False) for b in data["boxes"])
    rest = {k: v for k, v in data.items() if k != "boxes"}
    text = json.dumps(rest, ensure_ascii=False, indent=2)
    text = text[:-2] + ',\n  "boxes": [\n    ' + boxes + "\n  ]\n}\n"
    (OUT / f"{map_id}.json").write_text(text, encoding="utf-8")


