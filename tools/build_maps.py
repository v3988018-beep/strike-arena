"""Собирает карты Strike Arena в public/maps/*.json.

Запуск:  python tools/build_maps.py

Каждый ящик карты: [x, z, ширина, глубина, высота, материал, (высота основания)].
Высота основания нужна для того, что висит в воздухе: крыши, перемычки над дверями,
верх окон, кроны деревьев. Карта — от -40 до 40 по x и z.
"""
import json
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "public" / "maps"


def border(mat, h=7):
    """Внешние стены по краю карты."""
    return [[0, -40.5, 82, 1, h, mat], [0, 40.5, 82, 1, h, mat],
            [-40.5, 0, 1, 82, h, mat], [40.5, 0, 1, 82, h, mat]]


def wall_x(x1, x2, z, h, mat, t, door=None, window=False):
    """Стена вдоль x от x1 до x2. door — ширина проёма по центру; window — окно по центру."""
    cx, length = (x1 + x2) / 2, x2 - x1
    if door:
        side = (length - door) / 2
        return [[x1 + side / 2, z, side, t, h, mat], [x2 - side / 2, z, side, t, h, mat],
                [cx, z, door, t, h - 2.3, mat, 2.3]]                       # перемычка над дверью
    if window:
        side = (length - 1.6) / 2
        return [[x1 + side / 2, z, side, t, h, mat], [x2 - side / 2, z, side, t, h, mat],
                [cx, z, 1.6, t, 1.1, mat], [cx, z, 1.6, t, h - 2.0, mat, 2.0]]  # под окном и над ним
    return [[cx, z, length, t, h, mat]]


def wall_z(z1, z2, x, h, mat, t, door=None, window=False):
    """То же, но стена вдоль z (меняем оси местами)."""
    return [[b[1], b[0], b[3], b[2], *b[4:]] for b in wall_x(z1, z2, x, h, mat, t, door, window)]


def house(cx, cz, w, d, h, doors, mat="brick", roof="roof", door=3.0, t=0.5):
    """Дом, в который можно зайти: стены с дверями (n/s/e/w) и окнами, сверху крыша.
    Центр дома лучше ставить на нечётные координаты — тогда проём двери совпадает
    с клеткой навигационной сетки ботов (клетки 2×2 м с центрами в нечётных точках)."""
    x1, x2, z1, z2 = cx - w / 2, cx + w / 2, cz - d / 2, cz + d / 2
    boxes = []
    boxes += wall_x(x1, x2, z2 - t / 2, h, mat, t, door if "n" in doors else None, "n" not in doors)
    boxes += wall_x(x1, x2, z1 + t / 2, h, mat, t, door if "s" in doors else None, "s" not in doors)
    boxes += wall_z(z1 + t, z2 - t, x2 - t / 2, h, mat, t, door if "e" in doors else None, "e" not in doors)
    boxes += wall_z(z1 + t, z2 - t, x1 + t / 2, h, mat, t, door if "w" in doors else None, "w" not in doors)
    boxes.append([cx, cz, w + 0.6, d + 0.6, 0.35, roof, h])
    return boxes


def tree(x, z):
    return [[x, z, 0.6, 0.6, 2.6, "wood"], [x, z, 2.6, 2.6, 2.4, "pine", 2.4]]


def ragged_x(x1, x2, z, mat, h=(3.0, 3.6, 2.7, 3.3), t=1.0, seg=2.5):
    """Рваная стена вдоль x: куски разной высоты чуть смещены вперёд-назад — выглядит живее ровной,
    но сквозь неё не видно (куски стыкуются без щелей)."""
    boxes, x, i = [], x1, 0
    while x < x2 - 0.01:
        w = min(seg, x2 - x)
        boxes.append([round(x + w / 2, 2), round(z + (0.25 if i % 2 else -0.15), 2), w + 0.3, t, h[i % len(h)], mat])
        x += w
        i += 1
    return boxes


def ragged_z(z1, z2, x, mat, h=(3.0, 3.6, 2.7, 3.3), t=1.0, seg=2.5):
    return [[b[1], b[0], b[3], b[2], *b[4:]] for b in ragged_x(z1, z2, x, mat, h, t, seg)]


def mirror(boxes):
    """Отражение через центр карты (x, z) → (-x, -z) — для симметричных половин."""
    return [[-b[0], -b[1], *b[2:]] for b in boxes]


