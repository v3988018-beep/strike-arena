    def shelf_rack(x, z1, z2, see=(), mat="rack"):
        """Стеллаж вдоль z. На участках see = [(z_от, z_до)] — настоящие полки с просветами:
        сквозь них видно и можно стрелять (сидя — в нижний просвет, стоя — в верхний)."""
        out, z = [], z1
        for a, b in sorted(see):
            if a > z:
                out.append([x, round((z + a) / 2, 3), 1.2, round(a - z, 3), 4, mat])
            c, d = round((a + b) / 2, 3), round(b - a, 3)
            out += [[x, c, 1.2, d, 0.7, mat], [x, c, 1.2, d, 0.15, mat, 1.35],      # низ с коробками, полка
                    [x, c, 1.2, d, 0.15, mat, 2.4], [x, c, 1.2, d, 1.45, mat, 2.55],  # полка, верх с коробками
                    [x, c - d / 4, 1.0, d / 2.2, 0.85, "crate", 1.5]]                # коробка на полке — закрывает половину
            z = b
        if z2 > z:
            out.append([x, round((z + z2) / 2, 3), 1.2, round(z2 - z, 3), 4, mat])
        return out

